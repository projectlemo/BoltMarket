"""A small database layer over DB-API drivers.

PostgreSQL (psycopg 3) in production, SQLite for local development and tests. SQL is written
once with ``:name`` parameters and portable syntax; dialect differences are handled here.
"""
from __future__ import annotations

import json
import logging
import queue
import re
import sqlite3
import threading
from collections.abc import Iterator, Mapping
from contextlib import contextmanager
from datetime import UTC, datetime
from decimal import Decimal
from pathlib import Path
from typing import Any

log = logging.getLogger("bolt.db")

_PARAM = re.compile(r"(?<![:\w]):([A-Za-z_][A-Za-z0-9_]*)")
MIGRATIONS_DIR = Path(__file__).parent / "migrations"


class Json:
    """Wraps a value that must be stored in a JSON column."""

    __slots__ = ("value",)

    def __init__(self, value: Any) -> None:
        self.value = value


class DatabaseError(Exception):
    pass


class UniqueViolation(DatabaseError):
    pass


def utcnow() -> datetime:
    return datetime.now(UTC)


def to_pyformat(sql: str) -> str:
    """Convert ``:name`` parameters to psycopg's ``%(name)s`` (``::type`` casts are left alone)."""
    return _PARAM.sub(r"%(\1)s", sql.replace("%", "%%"))


# --- SQLite type handling ----------------------------------------------------------------

def _adapt_datetime(value: datetime) -> str:
    if value.tzinfo is None:
        value = value.replace(tzinfo=UTC)
    return value.astimezone(UTC).isoformat()


sqlite3.register_adapter(datetime, _adapt_datetime)
sqlite3.register_adapter(Decimal, str)
sqlite3.register_converter("TIMESTAMPTZ", lambda b: datetime.fromisoformat(b.decode()))
sqlite3.register_converter("BOOLEAN", lambda b: b not in (b"0", b"", b"f", b"false"))
sqlite3.register_converter("JSON", lambda b: json.loads(b))

_DIALECT_TOKENS = {
    "sqlite": {"{{pk}}": "INTEGER PRIMARY KEY AUTOINCREMENT", "{{json}}": "JSON", "{{blob}}": "BLOB"},
    "postgres": {"{{pk}}": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "{{json}}": "JSONB", "{{blob}}": "BYTEA"},
}


class Conn:
    """One connection inside one transaction."""

    def __init__(self, raw: Any, dialect: str) -> None:
        self.raw = raw
        self.dialect = dialect

    # -- helpers ------------------------------------------------------------------------
    @property
    def for_update(self) -> str:
        return " FOR UPDATE" if self.dialect == "postgres" else ""

    def _params(self, params: Mapping[str, Any]) -> dict[str, Any]:
        out: dict[str, Any] = {}
        for key, value in params.items():
            if isinstance(value, (Json, dict, list)):
                raw_value = value.value if isinstance(value, Json) else value
                if self.dialect == "postgres":
                    from psycopg.types.json import Jsonb  # type: ignore[import-not-found]

                    out[key] = None if raw_value is None else Jsonb(raw_value)
                else:
                    out[key] = None if raw_value is None else json.dumps(raw_value, separators=(",", ":"), default=str)
            else:
                out[key] = value
        return out

    def _execute(self, sql: str, params: Mapping[str, Any]) -> Any:
        bound = self._params(params)
        try:
            if self.dialect == "postgres":
                return self.raw.execute(to_pyformat(sql), bound)
            return self.raw.execute(sql, bound)
        except sqlite3.IntegrityError as exc:
            if "UNIQUE" in str(exc):
                raise UniqueViolation(str(exc)) from exc
            raise DatabaseError(str(exc)) from exc
        except Exception as exc:
            if getattr(exc, "sqlstate", None) == "23505":
                raise UniqueViolation(str(exc)) from exc
            raise

    @staticmethod
    def _row(cursor: Any, row: Any) -> dict[str, Any]:
        if isinstance(row, dict):
            return row
        if isinstance(row, sqlite3.Row):
            return dict(zip(row.keys(), tuple(row), strict=True))
        cols = [d[0] for d in cursor.description]
        return dict(zip(cols, row, strict=False))

    # -- queries ------------------------------------------------------------------------
    def one(self, sql: str, **params: Any) -> dict[str, Any] | None:
        cur = self._execute(sql, params)
        row = cur.fetchone()
        return None if row is None else self._row(cur, row)

    def all(self, sql: str, **params: Any) -> list[dict[str, Any]]:
        cur = self._execute(sql, params)
        return [self._row(cur, r) for r in cur.fetchall()]

    def val(self, sql: str, **params: Any) -> Any:
        row = self.one(sql, **params)
        return None if row is None else next(iter(row.values()))

    def exec(self, sql: str, **params: Any) -> int:
        cur = self._execute(sql, params)
        return int(cur.rowcount or 0)

    def insert(self, table: str, data: Mapping[str, Any]) -> dict[str, Any]:
        cols = list(data)
        sql = f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(':' + c for c in cols)}) RETURNING *"
        row = self.one(sql, **data)
        assert row is not None
        return row

    def update(self, table: str, row_id: int, data: Mapping[str, Any]) -> dict[str, Any] | None:
        if not data:
            return self.one(f"SELECT * FROM {table} WHERE id = :id", id=row_id)
        sets = ", ".join(f"{c} = :{c}" for c in data)
        return self.one(f"UPDATE {table} SET {sets} WHERE id = :id RETURNING *", **data, id=row_id)

    def get(self, table: str, row_id: int, *, lock: bool = False) -> dict[str, Any] | None:
        return self.one(f"SELECT * FROM {table} WHERE id = :id" + (self.for_update if lock else ""), id=row_id)


class Database:
    def __init__(self, url: str, *, pool_size: int = 10) -> None:
        self.url = url
        self._pool: queue.LifoQueue[Any] = queue.LifoQueue()
        self._lock = threading.Lock()
        self._created = 0
        self._max = max(1, pool_size)
        if url.startswith("sqlite"):
            self.dialect = "sqlite"
            path = url.split(":///", 1)[1] if ":///" in url else ":memory:"
            if path != ":memory:":
                Path(path).parent.mkdir(parents=True, exist_ok=True)
            self._target = path
        elif url.startswith(("postgres://", "postgresql://", "postgresql+psycopg://")):
            self.dialect = "postgres"
            self._target = "postgresql://" + url.split("://", 1)[1]
        else:
            raise ValueError("DATABASE_URL must start with sqlite:/// or postgresql://")

    # -- connections --------------------------------------------------------------------
    def _connect(self) -> Any:
        if self.dialect == "sqlite":
            raw = sqlite3.connect(
                self._target, detect_types=sqlite3.PARSE_DECLTYPES, timeout=30, check_same_thread=False, isolation_level=None
            )
            raw.row_factory = sqlite3.Row
            raw.execute("PRAGMA foreign_keys = ON")
            raw.execute("PRAGMA busy_timeout = 30000")
            if self._target != ":memory:":
                raw.execute("PRAGMA journal_mode = WAL")
            return raw
        import psycopg  # type: ignore[import-not-found]
        from psycopg.rows import dict_row  # type: ignore[import-not-found]

        return psycopg.connect(self._target, row_factory=dict_row, autocommit=False)

    def _acquire(self) -> Any:
        try:
            return self._pool.get_nowait()
        except queue.Empty:
            pass
        with self._lock:
            if self._created < self._max:
                self._created += 1
                try:
                    return self._connect()
                except Exception:
                    self._created -= 1
                    raise
        return self._pool.get(timeout=30)

    def _release(self, raw: Any, healthy: bool) -> None:
        if healthy and not getattr(raw, "closed", False):
            self._pool.put(raw)
            return
        try:
            raw.close()
        except Exception as exc:  # pragma: no cover - best effort
            log.debug("closing a broken connection failed: %s", exc)
        with self._lock:
            self._created -= 1

    @contextmanager
    def tx(self) -> Iterator[Conn]:
        raw = self._acquire()
        healthy = True
        try:
            if self.dialect == "sqlite":
                raw.execute("BEGIN IMMEDIATE")
            yield Conn(raw, self.dialect)
            if self.dialect == "sqlite":
                raw.execute("COMMIT")
            else:
                raw.commit()
        except BaseException:
            try:
                if self.dialect == "sqlite":
                    if raw.in_transaction:
                        raw.execute("ROLLBACK")
                else:
                    raw.rollback()
            except Exception:
                healthy = False
            raise
        finally:
            self._release(raw, healthy)

    def close(self) -> None:
        while True:
            try:
                raw = self._pool.get_nowait()
            except queue.Empty:
                break
            try:
                raw.close()
            except Exception as exc:  # pragma: no cover
                log.debug("closing connection failed: %s", exc)
        self._created = 0

    def ping(self) -> bool:
        try:
            with self.tx() as c:
                return c.val("SELECT 1 AS ok") == 1
        except Exception:
            return False

    # -- migrations ---------------------------------------------------------------------
    def render_sql(self, sql: str) -> str:
        for token, value in _DIALECT_TOKENS[self.dialect].items():
            sql = sql.replace(token, value)
        return sql

    def migrate(self, directory: Path = MIGRATIONS_DIR) -> list[str]:
        applied: list[str] = []
        with self.tx() as c:
            if self.dialect == "postgres":
                c.exec("SELECT pg_advisory_xact_lock(7314159)")
            c.exec("CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL)")
            done = {r["version"] for r in c.all("SELECT version FROM schema_migrations")}
            for path in sorted(directory.glob("*.sql")):
                version = path.stem
                if version in done:
                    continue
                for statement in split_sql(self.render_sql(path.read_text(encoding="utf-8"))):
                    c.exec(statement)
                c.exec("INSERT INTO schema_migrations (version, applied_at) VALUES (:v, :t)", v=version, t=utcnow())
                applied.append(version)
                log.info("applied migration %s", version)
        return applied


def split_sql(script: str) -> list[str]:
    statements: list[str] = []
    current: list[str] = []
    for line in script.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("--"):
            continue
        current.append(line)
        if stripped.endswith(";"):
            statements.append("\n".join(current).rstrip().rstrip(";"))
            current = []
    if current:
        statements.append("\n".join(current))
    return statements
