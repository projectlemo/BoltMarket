export const COUNTRY_CODES = Object.keys(COUNTRY_NAMES);

export function countryNamesFor(codes: readonly string[], lang: 'en' | 'ar'): string[] {
  return codes.map((c) => COUNTRY_NAMES[c]?.[lang === 'ar' ? 1 : 0] ?? c);
}

export function countryOptions(lang: 'en' | 'ar'): { code: string; name: string }[] {
  const names = countryNamesFor(COUNTRY_CODES, lang);
  return COUNTRY_CODES.map((code, i) => ({ code, name: names[i] })).sort((a, b) => a.name.localeCompare(b.name, lang));
}
